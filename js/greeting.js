export function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function fill(str, { gender = 'm', sender = 'team', vars = {} } = {}) {
  return str
    .replace(/«([^|»]*)\|([^»]*)»/g, (_, m, f) => (gender === 'f' ? f : m))
    .replace(/⟨([^|⟩]*)\|([^⟩]*)⟩/g, (_, we, i) => (sender === 'me' ? i : we))
    .replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** "א, ב וג" — Hebrew list join; the conjunction ו attaches to the last item. */
export function joinHe(items) {
  if (items.length <= 1) return items.join('');
  return `${items.slice(0, -1).join(', ')} ו${items[items.length - 1]}`;
}

